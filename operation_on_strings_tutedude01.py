# counting  substring from a string
# count()
# string.count(substring)
s1 = "we are learning python, and python is easy."
# s1.count('python')
print(s1.count('python'))
print(s1.count('p'))
print(s1.count(' '))
print(s1.count('.'))
print(s1.count(','))

# upper-case and lower-case
s2 = "Computational Fluid Dynamics"
print(s2.upper())
print(s2.lower())
print(s2.capitalize())
print(s2.title())
print(s2.startswith("C"))
print(s2.startswith("f"))
print(s2.endswith("s"))
