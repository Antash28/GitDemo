# slicing in python
s1 = "Hello World"
print(s1)

# length of s1
length = len(s1)
print(length)

# another way to print
print(len(s1))

# indexing
print("First Character", s1[0])
print("Last Character", s1[-1])

# slicing syntac
# string[start : end : step]
# [end-index] will not be printed
print(s1[2:7:1])
print(type(s1))
